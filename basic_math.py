def main():
    print("7 - 3 = {}".format(7 - 3))  # subtraction
    print("2 + 4  = {}".format(2 + 4))  # addition
    print("8 * 6 = {}".format(8 * 6))  # multiplication
    print("4 / 2 = {}".format(4 / 2))  # division
    print("2 + 5 *3 = {}".format(2 + 5 * 3))  # bedmas
    print("2^3 = {}".format(2 ^ 3))  # bitwise operator
    print("2**3 = {}".format(2**3))  # exponent
    print("16**0.5 = {}".format(16**0.5))  # square root
    print("10 % 7 = {}".format(10 % 7))  # modulo remainder


if __name__ == "__main__":
    main()
